function normalizeExerciseName(value: string): string {
  return value
    .normalize("NFKD")
    .toLowerCase()
    .replace(/[‐‑‒–—_-]+/g, " ")
    .replace(/[^a-z0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Translate exercise descriptions for display only.
 * Original database content is preserved.
 */
export function translateExerciseContent(
  exerciseName: string | null | undefined,
  field: ExerciseContentField,
  originalValue: string | null | undefined,
  language: Language,
): string {
  if (!originalValue) return "";

  if (language !== "fa" || !exerciseName) {
    return originalValue;
  }

  const normalizedName = normalizeExerciseName(exerciseName);
  const translation = persianContent[normalizedName]?.[field];

  return translation ?? originalValue;
}
